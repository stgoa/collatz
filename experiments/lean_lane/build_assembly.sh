#!/bin/sh
# Regenerates V004_Assembly.lean, the file that is compiled for V004-iii, from the
# three parts. The first two are the verified files of V004-i and V004-ii with
# their `import Mathlib` line removed; the third is the assembly proper.
set -e
cd "$(dirname "$0")"
{
  echo 'import Mathlib'
  echo
  echo '/-! `V004_Assembly.lean` is generated by `build_assembly.sh`; edit the parts, not this file. -/'
  echo
  sed '1{/^import Mathlib$/d;}' OddEventuallyPeriodic.lean
  echo
  sed '1{/^import Mathlib$/d;}' KernelClosure.lean
  echo
  cat V004_Final.lean
} > V004_Assembly.lean
echo "wrote V004_Assembly.lean ($(wc -l < V004_Assembly.lean) lines)"
