#!/bin/sh
# Regenerates ReverseClosure_Assembly.lean, the file that is compiled for V007-a, from
# V004_Assembly.lean (itself regenerated here by build_assembly.sh), the verified
# ScalarInterface.lean (V005-a) with its `import Mathlib` line removed, and the
# assembly proper, ReverseClosure_Final.lean.
set -e
cd "$(dirname "$0")"
sh build_assembly.sh >/dev/null
{
  echo 'import Mathlib'
  echo
  echo '/-! `ReverseClosure_Assembly.lean` is generated by `build_reverse_assembly.sh`; edit the parts, not this file. -/'
  echo
  sed '1{/^import Mathlib$/d;}' V004_Assembly.lean
  echo
  sed '1{/^import Mathlib$/d;}' ScalarInterface.lean
  echo
  cat ReverseClosure_Final.lean
} > ReverseClosure_Assembly.lean
echo "wrote ReverseClosure_Assembly.lean ($(wc -l < ReverseClosure_Assembly.lean) lines)"
