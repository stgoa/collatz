"""Sidekick probe: independent check of main's V003 digit-count rigidity (experiments/viewpoints/V003/digit_sum.md,
main 2ac44ef): for n_k = 32(2^k-1)+9, s2(n_k) = k+2 and s2(3n_k+1) = k+3 for every k >= 2 (checked to k = 3000);
the three small sources 5, 13, 23 connect weights 1..4; hence any invariant h = F(s2(n)) is constant. Also: the
d-controls 1_{5|n}, 1_{61|n} do not factor through s2 (witnesses 3 vs 5 and 31 vs 61), and Thue-Morse
(s2 mod 2) is not invariant (5 -> 16). Brute-force cross-check: for every odd n < 2*10^5, s2(n) and s2(3n+1)
lie in one class of the union-find on weights generated by all such pairs, and that union-find has one class.
Standard library. Run without -O.
"""
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent


def s2(n):
    return bin(n).count("1")


def main():
    for k in range(2, 3001):
        n = 32*(2**k - 1) + 9
        assert n % 2 == 1 and n > 1 and s2(n) == k + 2 and s2(3*n + 1) == k + 3
    assert [(n, 3*n + 1, s2(n), s2(3*n + 1)) for n in (5, 13, 23)] == [(5, 16, 2, 1), (13, 40, 3, 2), (23, 70, 4, 3)]
    assert s2(3) == s2(5) == 2 and (3 % 5 == 0) != (5 % 5 == 0)
    assert s2(31) == s2(61) == 5 and (31 % 61 == 0) != (61 % 61 == 0)
    assert s2(5) % 2 != s2(16) % 2
    parent = {}
    def f(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for n in range(3, 2*10**5, 2):
        a, b = f(s2(n)), f(s2(3*n + 1))
        if a != b:
            parent[a] = b
    classes = {f(w) for w in parent}
    assert len(classes) == 1
    out = {"probe": "v003_digit_count_check", "main": "2ac44ef", "k_range": [2, 3000],
           "weights_connected_by_small_odd_n": sorted(parent)[:3] + ["..."] , "result": "PASS"}
    (HERE / "v003_digit_count_check.json").write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
