"""Sidekick probe: independent checks of main's C008 (experiments/cycle_spectrum/C008, main 93117c0).

(1) Sorted-rank law on every ordered census cycle with q > 1 (q <= L): with um + vA = 1 and t = 2^u 3^v mod q,
    t^m = 2 and t^A = 3 (mod q), and the j-th smallest normalized state satisfies z_[j] = L t^j (mod q).
(2) Cyclicity: <2,3> mod q is cyclic for every ordered cycle's q (it is generated by t); no ordered census cycle has
    35, 65 or 91 dividing q; <2,3> mod 35, 65, 91 is noncyclic.
(3) The two q = 2^27 - 3^17 = 5,077,565 period-17 counterexamples: actual raw cycles of 3x+q from L = 446,400,719 and
    L = 365,289,811, reduced denominator q, ordered, q <= L, B = 3 and 2; their height-residue sets modulo 5.
Standard library. Run without -O.
"""
from fractions import Fraction as Fr
from math import gcd
from pathlib import Path
import json
import sys

HERE = Path(__file__).resolve().parent


def v2(n):
    return (n & -n).bit_length() - 1


def CD(z):
    A, C, m = 0, 0, len(z)
    for j, a in enumerate(z):
        C += 3**(m - 1 - j) * 2**A
        A += a
    return C, 2**A - 3**m


def cycle_from(q, n0):
    ns, vals, x = [], [], n0
    while True:
        y = 3 * x + q
        e = v2(y)
        ns.append(x)
        vals.append(e)
        x = y >> e
        if x == n0:
            return ns, vals
        assert len(ns) < 10**5


def profile(ns):
    m, L = len(ns), min(ns)
    h = [((n // L).bit_length() - 1) for n in ns]
    z = [Fr(n, 2**hi) for n, hi in zip(ns, h)]
    order = sorted(range(m), key=lambda i: z[i])
    rank = {i: r for r, i in enumerate(order)}
    shifts = {(rank[(i + 1) % m] - rank[i]) % m for i in range(m)}
    return {"m": m, "L": L, "B": max(h), "h": h, "z": z, "order": order, "ordered": len(shifts) == 1}


def egcd(a, b):
    if b == 0:
        return a, 1, 0
    g, x, y = egcd(b, a % b)
    return g, y, x - (a // b) * y


def mod_pow(b, e, q):
    return pow(b, e, q) if e >= 0 else pow(pow(b, -1, q), -e, q)


def cyclic_subgroup_23(q):
    # <2,3> mod q is cyclic iff its order equals the order of some element; compute group by closure
    elems = {1}
    frontier = [1]
    while frontier:
        x = frontier.pop()
        for g in (2, 3):
            y = x * g % q
            if y not in elems:
                elems.add(y)
                frontier.append(y)
    order = len(elems)
    def ordr(x):
        k, y = 1, x
        while y != 1:
            y = y * x % q
            k += 1
        return k
    return any(ordr(x) == order for x in elems)


def part1_2(path):
    data = json.load(open(path))
    seen, n_checked, bad35 = set(), 0, []
    for c in data["cycles"]:
        q, sc = c["reduced_denominator"], c["actual_scaling"]
        ns = [s // sc for s in c["states"]]
        key = (q, min(ns))
        if key in seen or len(ns) < 2:
            continue
        seen.add(key)
        pr = profile(ns)
        if not (pr["ordered"] and q <= pr["L"] and q > 1):
            continue
        i0 = ns.index(min(ns))
        ns2, vals = cycle_from(q, ns[i0])
        m, A = len(vals), sum(vals)
        g, u, v = egcd(m, A)
        assert g == 1
        t = mod_pow(2, u, q) * mod_pow(3, v, q) % q
        assert pow(t, m, q) == 2 % q and pow(t, A, q) == 3 % q
        pr2 = profile(ns2)
        L = pr2["L"]
        for j, i in enumerate(pr2["order"]):
            zz = pr2["z"][i]
            lhs = zz.numerator * pow(zz.denominator, -1, q) % q
            assert lhs == L * pow(t, j, q) % q, (q, L, j)
        assert cyclic_subgroup_23(q)
        if any(q % d == 0 for d in (35, 65, 91)):
            bad35.append(q)
        n_checked += 1
    assert not bad35
    noncyclic = {d: not cyclic_subgroup_23(d) for d in (35, 65, 91)}
    assert all(noncyclic.values())
    return {"ordered_cycles_q_gt_1": n_checked, "noncyclic_23_mod": noncyclic}


def part3():
    q = 2**27 - 3**17
    assert q == 5077565
    out = []
    for L0, Bexp in ((446400719, 3), (365289811, 2)):
        ns, vals = cycle_from(q, L0)
        C, D = CD(tuple(vals))
        assert len(ns) == 17 and D // gcd(C, D) == q and min(ns) == L0
        pr = profile(ns)
        assert pr["ordered"] and q <= pr["L"] and pr["B"] == Bexp
        raw, normd = {}, {}
        for n, hi, zz in zip(ns, pr["h"], pr["z"]):
            raw.setdefault(hi, set()).add(n % 5)
            normd.setdefault(hi, set()).add(zz.numerator * pow(zz.denominator, -1, 5) % 5)
        out.append({"L": L0, "B": pr["B"], "raw_mod5_by_height": {k: sorted(v) for k, v in sorted(raw.items())},
                    "normalized_mod5_by_height": {k: sorted(v) for k, v in sorted(normd.items())}})
    return out


def main():
    out = {"probe": "c008_residue_check", "main": "93117c0", "sorted_rank_law_and_cyclicity": part1_2(sys.argv[1]),
           "q5077565_counterexamples": part3(), "result": "PASS"}
    (HERE / "c008_residue_check.json").write_text(json.dumps(out, indent=1) + "\n")
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
