#!/usr/bin/env python3
"""Generate MAP.md, the one-page index of the knowledge graph. Never edit MAP.md by hand.

    python3 tools/build_map.py

For every result the map shows two strengths:
- **status**: the node's own status;
- **chain**: the weakest status along its `depends_on`/`assumes` chain of results. A `reviewed` result
  that depends on a `written` one has chain `written`.
It also lists the open questions and external sources a result rests on, transitively ("rests on").
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nodes  # noqa: E402
import schema as S  # noqa: E402

ROOT = nodes.ROOT
HEADER = "<!-- Generated by tools/build_map.py from the nodes' frontmatter. Do not edit by hand. -->\n"


def _cell(s, limit=None) -> str:
    s = " ".join(str(s or "").split()).replace("|", "\\|")
    if limit and len(s) > limit:
        s = s[: limit - 1].rstrip() + "…"
    return s


def analyse(g: nodes.Graph):
    """Return {id: (chain_status, set of open-question/source ids rested on)}."""
    res = g.resolver()
    memo: dict[str, tuple] = {}

    def go(n: nodes.Node, stack: frozenset):
        if n.id in memo:
            return memo[n.id]
        if n.id in stack:            # cycles are reported by check.py
            return n.status, set()
        rank = S.LADDER.index(n.status) if n.status in S.LADDER else None
        rests: set = set()
        for t in n.list_field("depends_on") + n.list_field("assumes"):
            d = res.get(str(t))
            if d is None:
                continue
            if d.kind == "question" and d.status != "answered":
                rests.add(d.id)
            elif d.kind == "source":
                rests.add(d.id)
            elif d.kind in ("result", "attempt"):
                ch, r = go(d, stack | {n.id})
                rests |= r
                if ch in S.LADDER and rank is not None:
                    rank = min(rank, S.LADDER.index(ch))
        chain = S.LADDER[rank] if rank is not None else n.status
        memo[n.id] = (chain, rests)
        return memo[n.id]

    for n in g.nodes:
        go(n, frozenset())
    return memo


def link(n: nodes.Node) -> str:
    return f"[`{n.id}`]({n.rel})"


def render(g: nodes.Graph) -> str:
    info = analyse(g)
    by_kind = {k: [n for n in g.nodes if n.kind == k] for k in S.KINDS}
    areas = sorted({n.area for n in g.nodes if n.area} | {p.name for p in (ROOT / "areas").glob("*/")})
    out = ["# Map\n", HEADER,
           "The whole knowledge graph on one page. Each row links to its node file; read the area overviews for the narrative. "
           "Statuses are defined in [`conventions/SCHEMA.md`](conventions/SCHEMA.md).\n"]
    counts = ", ".join(f"{len(by_kind[k])} {k}{'' if len(by_kind[k]) == 1 else 's'}" for k in S.KINDS)
    out.append(f"**{counts}.**\n")

    users: dict[str, list] = {}
    for n in g.nodes:
        for t in n.list_field("assumes") + n.list_field("depends_on"):
            users.setdefault(str(t), []).append(n.id)

    open_q = [n for n in by_kind["question"] if n.status == "open"]
    out.append("## Frontier: open questions\n")
    if open_q:
        out.append("| Question | Area | Claim | Results resting on it |\n|---|---|---|---|")
        for n in sorted(open_q, key=lambda n: (n.area or "", n.id)):
            rest = sum(1 for m in g.nodes if n.id in info.get(m.id, (None, set()))[1])
            out.append(f"| {link(n)} | {n.area} | {_cell(n.meta.get('claim'), 160)} | {rest} |")
    else:
        out.append("None recorded yet.")
    out.append("")

    for area in areas:
        out.append(f"## Area: {area}\n")
        out.append(f"Overview: [`areas/{area}/OVERVIEW.md`](areas/{area}/OVERVIEW.md)\n")
        res = sorted((n for n in by_kind["result"] if n.area == area), key=lambda n: n.id)
        if res:
            out.append("### Results\n")
            out.append("| Result | Title | Status | Chain | Rests on | Lean |\n|---|---|---|---|---|---|")
            for n in res:
                chain, rests = info.get(n.id, (n.status, set()))
                out.append(f"| {link(n)} | {_cell(n.meta.get('title'), 90)} | {n.status} | {chain} | "
                           f"{', '.join(f'`{r}`' for r in sorted(rests)) or '—'} | {'yes' if n.list_field('lean') else ''} |")
            out.append("")
        att = sorted((n for n in by_kind["attempt"] if n.area == area), key=lambda n: n.id)
        if att:
            out.append("### Attempts (approaches that failed or stalled)\n")
            out.append("| Attempt | Title | Status |\n|---|---|---|")
            for n in att:
                out.append(f"| {link(n)} | {_cell(n.meta.get('title'), 110)} | {n.status} |")
            out.append("")
        qs = sorted((n for n in by_kind["question"] if n.area == area and n.status != "open"), key=lambda n: n.id)
        if qs:
            out.append("### Closed questions\n")
            out.append("| Question | Title | Status | Answered by |\n|---|---|---|---|")
            for n in qs:
                out.append(f"| {link(n)} | {_cell(n.meta.get('title'), 90)} | {n.status} | "
                           f"{', '.join(f'`{a}`' for a in n.list_field('answered_by')) or '—'} |")
            out.append("")

    if by_kind["source"]:
        out.append("## Sources (external inputs)\n")
        out.append("| Source | Title | Status | Used by |\n|---|---|---|---|")
        for n in sorted(by_kind["source"], key=lambda n: n.id):
            out.append(f"| {link(n)} | {_cell(n.meta.get('title'), 100)} | {n.status} | {len(users.get(n.id, []))} |")
        out.append("")

    aliases = sorted(((str(a), n) for n in g.nodes for a in n.list_field("aliases")), key=lambda x: x[0])
    if aliases:
        out.append("## Legacy IDs\n")
        out.append("Older documents cite results by series numbers (C011, S13, R71, V004, …). This table resolves them.\n")
        out.append("| Legacy ID | Node |\n|---|---|")
        for a, n in aliases:
            out.append(f"| {a} | {link(n)} |")
        out.append("")

    events = []
    for n in g.nodes:
        if n.meta.get("created"):
            events.append((str(n.meta["created"]), f"{link(n)} added ({n.kind})"))
        for r in n.list_field("reviewed_by"):
            if isinstance(r, dict) and r.get("date"):
                events.append((str(r["date"]), f"{link(n)} reviewed by {_cell(r.get('by'))}"))
    if events:
        out.append("## Recent activity\n")
        for d, e in sorted(events, key=lambda x: x[0], reverse=True)[:25]:
            out.append(f"- {d}: {e}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    g = nodes.load()
    if g.errors:
        for e in g.errors:
            print(f"error: {e}")
        return 1
    (ROOT / "MAP.md").write_text(render(g), encoding="utf-8")
    print(f"MAP.md: {len(g.nodes)} nodes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
